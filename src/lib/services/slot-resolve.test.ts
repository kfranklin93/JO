import { describe, expect, it } from 'vitest';
import { freeSlots, type Slot } from '@/lib/services/availability';
import {
  describeSlot,
  describeSlotDay,
  describeSlotShort,
  describeSlotTime,
} from '@/lib/services/slot-label';
import { parseIsoInstant, resolveSlotLabel } from '@/lib/services/slot-resolve';

/**
 * Resolving what the model said back to the slot it meant.
 *
 * The bug being covered is a multi-turn one, and it cannot be seen in a single
 * request. The assistant calls check_availability, reads times out, and the
 * turn ends. Nothing stores the tool result — `chat_messages` holds a role and
 * text — so when the client replies "3:30 works" in the *next* request, the
 * model no longer has the ISO instants. It passes the only form of the time it
 * still has, which is the sentence it wrote: "3:30 PM Eastern Time".
 *
 * Two properties are being pinned here, and they pull against each other.
 *
 * Recognition: the realistic phrasings must land on the right slot, including
 * the ones no formatter in slot-label.ts produces, because the model writes
 * "October 30 at 3:30 PM" as readily as it echoes a full label.
 *
 * Refusal: a phrasing that fits more than one free slot must resolve to none of
 * them. "3:30 PM" is free on most days of a three-week horizon, and booking the
 * soonest would put a client in Joey's calendar on a day they never agreed to.
 * Every ambiguous case below asserts the outcome is *not* resolved, which is
 * the assertion that would fail if someone later "improved" this by taking the
 * first match.
 *
 * Slots are generated by the real `freeSlots` at a fixed clock rather than
 * hand-written, so the grid, the business hours and the DST boundary in the
 * middle of the horizon are the production ones. Monday 27 October 2025, 9 AM
 * Eastern: the horizon runs to 17 November and crosses the end of daylight
 * saving on 2 November.
 */

const NOW = new Date('2025-10-27T13:00:00.000Z');

/** Every free slot in the horizon, nothing booked. */
const SLOTS = freeSlots(NOW);

/** One slot by its Eastern date and `HH:MM`, so the tests read as a calendar. */
function slotAt(date: string, time: string): Slot {
  const slot = SLOTS.find((candidate) => candidate.date === date && candidate.time === time);
  if (!slot) throw new Error(`test fixture: no free slot at ${date} ${time}`);
  return slot;
}

/** Thursday 30 October, 3:30 PM Eastern — 19:30 UTC, still daylight saving. */
const THURSDAY = slotAt('2025-10-30', '15:30');

/** Thursday 6 November, 3:30 PM Eastern — 20:30 UTC, after the switch. */
const AFTER_DST = slotAt('2025-11-06', '15:30');

/** Only the slots on one Eastern date, for the cases a day makes unambiguous. */
function slotsOn(date: string): Slot[] {
  return SLOTS.filter((slot) => slot.date === date);
}

describe('the fixture is the calendar the tests assume', () => {
  it('puts the Thursday slot where daylight saving says it is', () => {
    expect(THURSDAY.startsAt.toISOString()).toBe('2025-10-30T19:30:00.000Z');
    expect(AFTER_DST.startsAt.toISOString()).toBe('2025-11-06T20:30:00.000Z');
  });

  it('has 3:30 PM free on several days, which is what makes a bare time ambiguous', () => {
    const halfPastThree = SLOTS.filter((slot) => slot.time === '15:30');

    expect(halfPastThree.length).toBeGreaterThan(1);
  });
});

/**
 * The fast path. An exact instant is used as given, and nothing else is.
 */
describe('parseIsoInstant', () => {
  it('accepts the value check_availability hands the model', () => {
    const parsed = parseIsoInstant(THURSDAY.startsAt.toISOString());

    expect(parsed?.getTime()).toBe(THURSDAY.startsAt.getTime());
  });

  it('accepts an offset instead of Z', () => {
    expect(parseIsoInstant('2025-10-30T15:30:00-04:00')?.toISOString()).toBe(
      '2025-10-30T19:30:00.000Z',
    );
  });

  it('keeps reading a zone-less timestamp as UTC, as the server always has', () => {
    expect(parseIsoInstant('2025-10-30T19:30:00')?.toISOString()).toBe(
      '2025-10-30T19:30:00.000Z',
    );
  });

  it('refuses a string Date would parse in the server’s zone', () => {
    // The quiet version of this whole bug. `new Date('October 30, 2025 3:30
    // PM')` is a valid date on Netlify — 3:30 PM *UTC*, which is 11:30 AM in
    // Atlanta — so accepting it would book a real slot four hours from the one
    // the client said. It goes to the resolver instead, where the only
    // reachable instants are genuinely free slots.
    expect(parseIsoInstant('October 30, 2025 3:30 PM')).toBeUndefined();
  });

  it.each([
    ['a spoken label', '3:30 PM Eastern Time'],
    ['a full spoken label', 'Thursday, October 30 at 3:30 PM Eastern Time'],
    ['a date with no time', '2025-10-30'],
    ['an epoch number as a string', '1761852600000'],
    ['nothing', ''],
  ])('refuses %s', (_case, value) => {
    expect(parseIsoInstant(value)).toBeUndefined();
  });
});

describe('resolveSlotLabel — the labels this codebase produces', () => {
  it('resolves the long label the assistant reads out', () => {
    const resolution = resolveSlotLabel(describeSlot(THURSDAY.startsAt), SLOTS);

    expect(resolution).toEqual({ outcome: 'resolved', slot: THURSDAY });
  });

  it('resolves the short label', () => {
    const resolution = resolveSlotLabel(describeSlotShort(THURSDAY.startsAt), SLOTS);

    expect(resolution).toEqual({ outcome: 'resolved', slot: THURSDAY });
  });

  it('resolves the dashboard’s day and time written together', () => {
    const written = `${describeSlotDay(THURSDAY.startsAt)} ${describeSlotTime(THURSDAY.startsAt)}`;

    expect(resolveSlotLabel(written, SLOTS)).toEqual({
      outcome: 'resolved',
      slot: THURSDAY,
    });
  });

  /**
   * The drift guard.
   *
   * slot-label.ts owns the wording and this module owns reading it back, and
   * nothing in the type system ties the two together — a future change to the
   * formatters there would silently stop resolution working here, and the
   * symptom would be the original production bug returning. So every formatter
   * is exercised against every slot of a day rather than one sample.
   */
  it('reads back every formatter for every slot of a day', () => {
    const day = slotsOn('2025-10-30');
    expect(day.length).toBeGreaterThan(10);

    for (const slot of day) {
      for (const label of [
        describeSlot(slot.startsAt),
        describeSlotShort(slot.startsAt),
        `${describeSlotDay(slot.startsAt)} ${describeSlotTime(slot.startsAt)}`,
      ]) {
        expect(resolveSlotLabel(label, SLOTS), label).toEqual({
          outcome: 'resolved',
          slot,
        });
      }
    }
  });

  it('applies the zone at the slot’s own date, not a fixed offset', () => {
    // Same wall clock, a week later, the other side of the DST switch.
    const resolution = resolveSlotLabel('November 6 at 3:30 PM Eastern Time', SLOTS);

    expect(resolution).toEqual({ outcome: 'resolved', slot: AFTER_DST });
    expect(AFTER_DST.startsAt.getUTCHours()).toBe(20);
  });
});

describe('resolveSlotLabel — the phrasings the model actually writes', () => {
  it.each([
    ['a month and a day', 'October 30 at 3:30 PM'],
    ['an abbreviated month', 'Oct 30 at 3:30 PM'],
    ['an ordinal', 'October 30th at 3:30 PM'],
    ['the time first', '3:30pm on October 30'],
    ['a slash date', '10/30 at 3:30 PM'],
    ['a slash date with a year', '10/30/2025 at 3:30 PM'],
    ['an ISO date with a spoken time', '2025-10-30 3:30 PM'],
    ['the seasonal abbreviation it was told not to use', 'October 30 at 3:30 PM EDT'],
    ['the other seasonal abbreviation', 'October 30 at 3:30 PM EST'],
    ['shouting', 'THURSDAY, OCTOBER 30 AT 3:30 PM EASTERN TIME'],
    ['untidy whitespace', '  October  30   at  3:30   PM  '],
    ['periods in the meridiem', 'October 30 at 3:30 p.m.'],
    ['a weekday as well as the date', 'Thursday, October 30, 3:30 PM'],
  ])('resolves %s', (_case, requested) => {
    expect(resolveSlotLabel(requested, SLOTS)).toEqual({
      outcome: 'resolved',
      slot: THURSDAY,
    });
  });

  it('resolves an hour with no minutes to the top of the hour', () => {
    const threeOClock = slotAt('2025-10-30', '15:00');

    expect(resolveSlotLabel('October 30 at 3 PM', SLOTS)).toEqual({
      outcome: 'resolved',
      slot: threeOClock,
    });
  });

  it('resolves a weekday and a time when only one such day is free', () => {
    // The narrowed candidate list is the realistic shape of this: by the time a
    // client is choosing, most of the week is booked.
    const oneThursday = slotsOn('2025-10-30');

    expect(resolveSlotLabel('Thursday at 3:30 PM', oneThursday)).toEqual({
      outcome: 'resolved',
      slot: THURSDAY,
    });
  });

  it('tells morning from afternoon', () => {
    const morning = slotAt('2025-10-30', '09:30');

    expect(resolveSlotLabel('October 30 at 9:30 AM', SLOTS)).toEqual({
      outcome: 'resolved',
      slot: morning,
    });
    expect(resolveSlotLabel('October 30 at 9:30 PM', SLOTS)).toEqual({
      outcome: 'no_match',
    });
  });
});

/**
 * The case that matters most.
 *
 * A label that names a time but not a day fits many free slots, and resolving
 * it would book the wrong day silently. A client who has to answer one more
 * question has lost nothing; a client who turns up on the wrong Thursday has.
 */
describe('resolveSlotLabel — ambiguity is refused, never guessed', () => {
  it('refuses a bare time, which is the exact string the model passes', () => {
    const resolution = resolveSlotLabel('3:30 PM Eastern Time', SLOTS);

    expect(resolution.outcome).toBe('ambiguous');
    if (resolution.outcome !== 'ambiguous') throw new Error('unreachable');
    expect(resolution.matches.length).toBeGreaterThan(1);
    expect(resolution.matches.every((slot) => slot.time === '15:30')).toBe(true);
  });

  it('refuses the time-only formatter’s own output', () => {
    expect(resolveSlotLabel(describeSlotTime(THURSDAY.startsAt), SLOTS).outcome).toBe(
      'ambiguous',
    );
  });

  it('refuses a weekday without a date when the horizon has several', () => {
    const resolution = resolveSlotLabel('Thursday at 3:30 PM', SLOTS);

    // Three Thursdays between 27 October and 17 November, all free at 3:30.
    expect(resolution.outcome).toBe('ambiguous');
    if (resolution.outcome !== 'ambiguous') throw new Error('unreachable');
    expect(resolution.matches).toHaveLength(3);
  });

  it('does not quietly take the soonest match', () => {
    // The assertion that fails if this is ever "improved" into picking one.
    for (const requested of ['3:30 PM', 'Thursday at 3:30 PM', 'October at 3:30 PM']) {
      expect(resolveSlotLabel(requested, SLOTS).outcome).not.toBe('resolved');
    }
  });

  it('refuses a whole day with no time, since a day holds many slots', () => {
    expect(resolveSlotLabel('October 30', SLOTS).outcome).not.toBe('resolved');
  });
});

describe('resolveSlotLabel — strings it cannot account for', () => {
  it.each([
    ['a time off the grid', '3:07 PM Eastern Time'],
    ['a time outside business hours', 'October 30 at 7:00 AM'],
    ['the midday gap', 'October 30 at 12:15 PM'],
    ['two times at once', 'October 30 at 3:30 PM or 4:00 PM'],
    ['a relative week', 'next Thursday at 3:30 PM'],
    ['a relative day', 'tomorrow at 3:30 PM'],
    ['no time at all', 'sometime next week'],
    ['an instruction', 'book whatever is free at 3:30 PM, it does not matter which day'],
    ['nothing', ''],
    ['an impossible clock', 'October 30 at 25:00 PM'],
  ])('refuses %s', (_case, requested) => {
    expect(resolveSlotLabel(requested, SLOTS)).toEqual({ outcome: 'no_match' });
  });

  it('refuses a date past the horizon', () => {
    expect(resolveSlotLabel('December 30 at 3:30 PM', SLOTS)).toEqual({
      outcome: 'no_match',
    });
  });

  it('refuses a weekday that contradicts the date it is given with', () => {
    // 30 October 2025 is a Thursday. A model that says Friday has reconstructed
    // the date from memory, which is the thing not to act on.
    expect(resolveSlotLabel('Friday, October 30 at 3:30 PM', SLOTS)).toEqual({
      outcome: 'no_match',
    });
  });

  /**
   * The security property, stated as a test.
   *
   * Resolution can only ever name a member of the candidate list, so a visitor
   * cannot reach a slot that is taken, outside business hours, or past the
   * horizon by crafting a string — including the perfectly-formed label of a
   * slot that has just been booked by somebody else.
   */
  it('cannot reach a slot that is no longer free, however well phrased', () => {
    const stillFree = SLOTS.filter((slot) => slot !== THURSDAY);

    expect(resolveSlotLabel(describeSlot(THURSDAY.startsAt), stillFree)).toEqual({
      outcome: 'no_match',
    });
  });

  it('resolves to nothing when nothing is free', () => {
    expect(resolveSlotLabel(describeSlot(THURSDAY.startsAt), [])).toEqual({
      outcome: 'no_match',
    });
  });
});
