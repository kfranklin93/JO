-- Adds 'assistant_chat' to the lead_source enum. NOT YET APPLIED.
--
-- Mirrors `leadSourceEnum` in src/lib/db/schema.ts, hand-written for the same
-- reason as the chat, appointment and mute files: this project has no migration
-- baseline, so schema changes are applied as SQL against the Neon branch you
-- mean to change.
--
-- Why the assistant needs it: every lead the chat captured until now was stored
-- as 'website_form', so Joey's dashboard could not tell a conversation from a
-- form submission.
--
-- ## ORDER OF OPERATIONS — this one is not optional
--
-- Postgres rejects an enum label it does not know, so this must be applied
-- BEFORE the code that writes 'assistant_chat' is deployed. Deploying first
-- means every chat lead capture fails on insert and the assistant stops
-- capturing leads entirely.
--
--   psql "$DATABASE_URL" -f src/lib/db/lead-source-schema.sql
--
-- Check which branch that URL points at first. Local .env.local and the Netlify
-- production variable have pointed at different Neon endpoints.
--
-- Then confirm the label is really there before pushing code:
--
--   SELECT e.enumlabel
--     FROM pg_enum e
--     JOIN pg_type t ON t.oid = e.enumtypid
--    WHERE t.typname = 'lead_source'
--    ORDER BY e.enumsortorder;
--
-- ## Why there is no BEGIN/COMMIT here
--
-- Unlike every other file in this directory, this one is deliberately not
-- wrapped in a transaction. `ALTER TYPE ... ADD VALUE` cannot run inside a
-- transaction block before Postgres 12, and from 12 onwards the new label still
-- cannot be used by a later statement in the same transaction until that
-- transaction commits. psql's autocommit default is therefore the one mode this
-- statement is safe in on every server version. Check the server with
-- `SELECT current_setting('server_version');` if a run surprises you.
--
-- Safe to run twice: IF NOT EXISTS makes a repeat a notice rather than an error.
-- No existing row changes — the labels already stored keep their values.

ALTER TYPE lead_source ADD VALUE IF NOT EXISTS 'assistant_chat';
